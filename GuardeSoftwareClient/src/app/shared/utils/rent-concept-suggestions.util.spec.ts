import {
  getLatestRentDebitMonth,
  parseRentConceptMonth,
  suggestRentConcepts,
} from './rent-concept-suggestions.util';

const debit = (concept: string) => ({ movementType: 'DEBITO', concept });
const today = new Date(2026, 10, 3); // 3 de noviembre de 2026

describe('rent concept suggestions', () => {
  describe('parseRentConceptMonth', () => {
    it('reads the month of the rent concepts generated by the system', () => {
      expect(parseRentConceptMonth('Alquiler Noviembre 2026')).toEqual({ year: 2026, month: 10 });
      expect(parseRentConceptMonth('Alquiler noviembre 2026 (Planificado)')).toEqual({ year: 2026, month: 10 });
      expect(parseRentConceptMonth('Alquiler Octubre 2026 (Proporcional 19 días)')).toEqual({ year: 2026, month: 9 });
      expect(parseRentConceptMonth('Alquiler Marzo 2027 (Reactivación Proporcional 5 días)')).toEqual({ year: 2027, month: 2 });
      expect(parseRentConceptMonth('Alquiler Setiembre 2026')).toEqual({ year: 2026, month: 8 });
    });

    it('ignores concepts that are not rent', () => {
      expect(parseRentConceptMonth('Interés por mora de Octubre 2026')).toBeNull();
      expect(parseRentConceptMonth('Pago alquiler Octubre 2026')).toBeNull();
      expect(parseRentConceptMonth('Proporcional')).toBeNull();
      expect(parseRentConceptMonth('Alquiler Mesinventado 2026')).toBeNull();
      expect(parseRentConceptMonth(null)).toBeNull();
    });
  });

  describe('getLatestRentDebitMonth', () => {
    it('takes the latest rent debit regardless of the order of the movements', () => {
      const latest = getLatestRentDebitMonth([
        debit('Alquiler Diciembre 2026'),
        debit('Alquiler Octubre 2026'),
        debit('Alquiler Enero 2027'),
        debit('Alquiler Noviembre 2026'),
      ]);
      expect(latest).toEqual({ year: 2027, month: 0 });
    });

    it('does not count credits or non rent debits', () => {
      const latest = getLatestRentDebitMonth([
        debit('Alquiler Octubre 2026'),
        debit('Interés por mora de Diciembre 2026'),
        { movementType: 'CREDITO', concept: 'Alquiler Diciembre 2026' },
      ]);
      expect(latest).toEqual({ year: 2026, month: 9 });
    });

    it('is null without rent debits', () => {
      expect(getLatestRentDebitMonth([])).toBeNull();
    });
  });

  describe('suggestRentConcepts', () => {
    it('suggests the current and next month when the client has no rent debits', () => {
      expect(suggestRentConcepts([], today)).toEqual(['Alquiler Noviembre 2026', 'Alquiler Diciembre 2026']);
    });

    it('suggests the two months after the ones already debited (October and November -> December and January)', () => {
      expect(suggestRentConcepts([debit('Alquiler Octubre 2026'), debit('Alquiler Noviembre 2026')], today))
        .toEqual(['Alquiler Diciembre 2026', 'Alquiler Enero 2027']);
    });

    it('suggests March and April when February is already debited', () => {
      expect(suggestRentConcepts([debit('Alquiler Febrero 2027')], today))
        .toEqual(['Alquiler Marzo 2027', 'Alquiler Abril 2027']);
    });

    it('follows the latest debit even when it is a planned future month', () => {
      expect(suggestRentConcepts([debit('Alquiler Noviembre 2026'), debit('Alquiler Abril 2027 (Planificado)')], today))
        .toEqual(['Alquiler Mayo 2027', 'Alquiler Junio 2027']);
    });
  });
});
